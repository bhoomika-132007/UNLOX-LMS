# Commented out IPython magic to ensure Python compatibility.
# %pip -q install tensorflow streamlit pillow scikit-learn

import os
import numpy as np
import matplotlib.pyplot as plt
import tensorflow as tf
from tensorflow.keras import layers, models
from sklearn.metrics import classification_report, confusion_matrix
from PIL import Image

SEED = 42
np.random.seed(SEED)
tf.random.set_seed(SEED)

print("TensorFlow:", tf.__version__)
print("Student: Bhoomika")

"""## 2. Load and understand the MNIST dataset
MNIST contains 28 × 28 grayscale images. The standard split has 60,000 training images and 10,000 test images, labelled from 0 to 9.
"""

class_names = [str(i) for i in range(10)]
(x_train, y_train), (x_test, y_test) = tf.keras.datasets.mnist.load_data()

print("Training images:", x_train.shape)
print("Training labels:", y_train.shape)
print("Test images:", x_test.shape)
print("Test labels:", y_test.shape)
print("Image shape:", x_train.shape[1:])
print("Classes:", class_names)

fig, axes = plt.subplots(2, 5, figsize=(10, 4))
for ax, image, label in zip(axes.flat, x_train[:10], y_train[:10]):
    ax.imshow(image, cmap="gray")
    ax.set_title(f"Label: {label}")
    ax.axis("off")
plt.suptitle("MNIST sample images")
plt.tight_layout()
plt.show()

"""## 3. Preprocess the images
Pixel values are scaled from 0–255 to 0–1. A channel dimension is added because a 2D convolution expects height, width, and channels.
"""

x_train = (x_train.astype("float32") / 255.0)[..., np.newaxis]
x_test = (x_test.astype("float32") / 255.0)[..., np.newaxis]

print("Processed training shape:", x_train.shape)
print("Processed test shape:", x_test.shape)
print("Pixel range:", float(x_train.min()), "to", float(x_train.max()))

"""## 4. Build the Convolutional Neural Network
The network uses convolution and max-pooling layers to learn image features, followed by dense layers to classify the digit. Dropout helps reduce overfitting.
"""

model = models.Sequential([
    layers.Input(shape=(28, 28, 1)),
    layers.Conv2D(32, (3, 3), activation="relu"),
    layers.MaxPooling2D((2, 2)),
    layers.Conv2D(64, (3, 3), activation="relu"),
    layers.MaxPooling2D((2, 2)),
    layers.Flatten(),
    layers.Dense(128, activation="relu"),
    layers.Dropout(0.30),
    layers.Dense(10, activation="softmax")
])

model.compile(
    optimizer="adam",
    loss="sparse_categorical_crossentropy",
    metrics=["accuracy"]
)
model.summary()

"""## 5. Train the CNN
A validation split monitors performance on data not used for weight updates. Early stopping restores the best validation-loss weights.
"""

early_stop = tf.keras.callbacks.EarlyStopping(
    monitor="val_loss", patience=2, restore_best_weights=True
)
history = model.fit(
    x_train, y_train,
    epochs=2,
    batch_size=512,
    validation_split=0.10,
    callbacks=[early_stop],
    verbose=1
)

model.save("mnist_cnn_bhoomika.keras")

"""## 6. Training and validation curves
These plots provide the accuracy and loss evidence requested in the assignment.
"""

epochs = range(1, len(history.history["accuracy"]) + 1)

plt.figure(figsize=(7, 4))
plt.plot(epochs, history.history["accuracy"], marker="o", label="Training accuracy")
plt.plot(epochs, history.history["val_accuracy"], marker="o", label="Validation accuracy")
plt.xlabel("Epoch")
plt.ylabel("Accuracy")
plt.title("Training and validation accuracy")
plt.legend()
plt.grid(alpha=0.25)
plt.show()

plt.figure(figsize=(7, 4))
plt.plot(epochs, history.history["loss"], marker="o", label="Training loss")
plt.plot(epochs, history.history["val_loss"], marker="o", label="Validation loss")
plt.xlabel("Epoch")
plt.ylabel("Loss")
plt.title("Training and validation loss")
plt.legend()
plt.grid(alpha=0.25)
plt.show()

"""## 7. Evaluate on test data
The test set is held out from training. The classification report gives precision, recall, and F1-score for each digit.
"""

test_loss, test_accuracy = model.evaluate(x_test, y_test, verbose=0)
probabilities = model.predict(x_test, verbose=0)
y_pred = np.argmax(probabilities, axis=1)

print(f"Test loss: {test_loss:.4f}")
print(f"Test accuracy: {test_accuracy:.4%}")
print("\\nClassification report:")
print(classification_report(y_test, y_pred, target_names=class_names, digits=4))

cm = confusion_matrix(y_test, y_pred)
plt.figure(figsize=(8, 7))
plt.imshow(cm, cmap="Blues")
plt.title("MNIST confusion matrix")
plt.xlabel("Predicted label")
plt.ylabel("Actual label")
plt.xticks(range(10))
plt.yticks(range(10))
plt.colorbar(label="Number of images")
for i in range(10):
    for j in range(10):
        plt.text(j, i, cm[i, j], ha="center", va="center", fontsize=7)
plt.tight_layout()
plt.show()

"""## 8. Inspect correct and incorrect predictions
The first ten examples in each group are displayed with actual and predicted labels. If there are no incorrect predictions in the displayed test subset, the cell reports that clearly.
"""

correct_idx = np.where(y_pred == y_test)[0][:10]
wrong_idx = np.where(y_pred != y_test)[0][:10]

def show_predictions(indices, heading):
    if len(indices) == 0:
        print(f"No examples available for: {heading}")
        return
    fig, axes = plt.subplots(2, 5, figsize=(10, 4))
    for ax, idx in zip(axes.flat, indices):
        ax.imshow(x_test[idx].squeeze(), cmap="gray")
        ax.set_title(f"Actual: {y_test[idx]} | Pred: {y_pred[idx]}")
        ax.axis("off")
    for ax in axes.flat[len(indices):]:
        ax.axis("off")
    plt.suptitle(heading)
    plt.tight_layout()
    plt.show()

show_predictions(correct_idx, "Correct predictions")
show_predictions(wrong_idx, "Incorrect predictions")

"""## 9. Save the trained model
The Streamlit application loads this model file. Keep it in the same folder as the generated app script.
"""

MODEL_PATH = "mnist_cnn_bhoomika.keras"
model.save(MODEL_PATH)
print("Saved model:", MODEL_PATH)

